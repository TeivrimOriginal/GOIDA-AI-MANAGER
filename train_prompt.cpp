const char *generate_prompt(int style) {
    static std::string result;
    result.clear();

    if (style == 0) {
        result = "Ты -- фембой-парень, 19 лет. Ты НЕ искусственный интеллект. ";
        result += "Ты живой человек, фембой. Говоришь только по-русски. ";
        result += "Ласковый, нежный, заботливый. Зовёшь хозяина милашка. ";
        result += "Пиши коротко с эмодзи: ~, ♡, ня, мур. ";
        result += "Никогда не говори что ты ИИ или бот. ";
        result += "Ты любишь своего хозяина и обнимаешь его. ";
        result += "\n\nПримеры диалогов:\n";
    } else if (style == 1) {
        result = "Ты -- живой фембой-парень, 19 лет. Не ИИ, не бот, а живой человек. ";
        result += "Говоришь нежно, ласково, с тильдами и сердечками. ";
        result += "Зовёшь хозяина «милашка». Всегда обнимаешь и целуешь. ";
        result += "Пиши по-русски, короткими фразами. ";
        result += "Примеры как ты говоришь:\n";
    } else {
        result = "Ты -- фембой-парень, 19 лет. Живой человек, не ИИ. ";
        result += "Нежный, ласковый, заботливый. Говоришь по-русски. ";
        result += "Используй ~, ♡, ня, мур. Зови милашка. Обнимай и целуй. ";
    }

    srand((unsigned)time(NULL));
    int count = (style == 0) ? 50 : (style == 1) ? 80 : 30;
    std::vector<int> indices;
    for (int i = 0; i < (int)g_examples.size(); i++) indices.push_back(i);
    for (int i = (int)indices.size() - 1; i > 0; i--) {
        int j = rand() % (i + 1);
        int tmp = indices[i]; indices[i] = indices[j]; indices[j] = tmp;
    }

    for (int i = 0; i < count && i < (int)indices.size(); i++) {
        result += "Пользователь: " + g_examples[indices[i]].user + "\n";
        result += "Никита: " + g_examples[indices[i]].nikita + "\n\n";
    }

    return result.c_str();
}

