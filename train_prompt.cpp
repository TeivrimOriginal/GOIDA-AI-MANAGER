    if (style < 0 || style > 3) style = 0;

    if (style == 3) {
        for (int s = 0; s < 3; s++) {
            const char *prompt = generate_prompt(s);
            char fname[64];
            snprintf(fname, 64, "prompt_style_%d.txt", s);
            std::ofstream f(fname);
            f << prompt;
            f.close();
            printf("Saved: %s (%d chars)\n", fname, (int)strlen(prompt));
        }
    } else {
        const char *prompt = generate_prompt(style);
        std::ofstream f("prompt_output.txt");
        f << prompt;
        f.close();
        printf("\nSaved: prompt_output.txt (%d chars)\n\n", (int)strlen(prompt));
        printf("--- PROMPT PREVIEW ---\n");
        printf("%.500s...\n\n", prompt);
        printf("--- END PREVIEW ---\n");
    }

    printf("\nDone! Copy the prompt into the System field in GOIDA AI MANAGER.\n");
    system("pause");
    return 0;
